#!/usr/bin/env node
/**
 * Bundles the MCP stdio bridge into a single self-contained ESM file so
 * external agents can launch it with only a Node.js runtime installed.
 */
import { build } from 'esbuild'
import { chmod, mkdir, readFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const entry = path.join(root, 'tools', 'mcp-server', 'src', 'index.ts')
const outfile = path.join(root, 'tools', 'mcp-server', 'dist', 'index.mjs')

const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))

await mkdir(path.dirname(outfile), { recursive: true })

await build({
  entryPoints: [entry],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  sourcemap: false,
  minify: false,
  legalComments: 'external',
  banner: {
    js: '#!/usr/bin/env node\n// Requirement Pulse MCP bridge — generated by scripts/build-mcp.mjs. Do not edit.'
  },
  define: {
    __PULSE_VERSION__: JSON.stringify(pkg.version)
  },
  logLevel: 'info'
})

try {
  await chmod(outfile, 0o755)
} catch {
  // Windows does not apply POSIX modes; the shebang still helps on Unix.
}

console.log(`[build-mcp] wrote ${path.relative(root, outfile)}`)
